#!/usr/bin/env node
// khouding authoring CLI, THE ORACLE.
//
// "A human never types an expected output." (VISION / architecture §5)
// This tool reads a problem.yaml (inputs only) + solution.<lang>, RUNS the
// solution against every case's stdin, and writes the generated expecteds to:
//   - expected.json  (committed machine artifact the ingester trusts)
//   - tests.md       (regenerated human mirror)
// problem.yaml stays input-only, so the oracle rule holds by construction.
//
// Commands:
//   node kh.mjs gen   [path]   generate/refresh expecteds for a problem/section/course/all
//   node kh.mjs check [path]   re-generate in memory and FAIL on drift (the CI guard)
//
// [path] may point at: a single problem folder, a section folder, a course
// folder, or be omitted (defaults to ../courses = everything).

import {
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
  statSync,
} from "node:fs";
import { join, resolve, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";
import { getRunner } from "./runners.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const COURSES_ROOT = resolve(__dirname, "..", "courses");

// ---------------------------------------------------------------------------
// grading-semantics normalization (architecture §5): normalize line endings
// (CRLF -> LF), an OS artifact, not a student skill. Nothing else is touched.
// ---------------------------------------------------------------------------
function normalizeEol(s) {
  return s.replace(/\r\n/g, "\n");
}

// ---------------------------------------------------------------------------
// discovery: find every problem folder under a given path.
// A "problem folder" is any directory containing a problem.yaml.
// ---------------------------------------------------------------------------
function findProblemDirs(startPath) {
  const out = [];
  const abs = resolve(startPath);
  if (!existsSync(abs)) {
    throw new Error(`path does not exist: ${abs}`);
  }
  (function walk(dir) {
    if (existsSync(join(dir, "problem.yaml"))) {
      out.push(dir);
      return; // a problem folder has no nested problem folders
    }
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      let st;
      try {
        st = statSync(full);
      } catch {
        continue;
      }
      if (st.isDirectory() && entry !== "node_modules" && !entry.startsWith("."))
        walk(full);
    }
  })(abs);
  return out.sort();
}

// ---------------------------------------------------------------------------
// generate expecteds for ONE problem folder.
// returns { problem, cases: [{ stdin, note, expected }], languageUsed }
// ---------------------------------------------------------------------------
function generateForProblem(problemDir) {
  const yamlPath = join(problemDir, "problem.yaml");
  const raw = readFileSync(yamlPath, "utf8");
  const spec = parseYaml(raw);

  if (!spec || typeof spec !== "object")
    throw new Error(`${yamlPath}: not a valid problem.yaml`);
  if (!Array.isArray(spec.cases) || spec.cases.length === 0)
    throw new Error(`${yamlPath}: 'cases' is missing or empty`);
  if (!Array.isArray(spec.languages) || spec.languages.length === 0)
    throw new Error(`${yamlPath}: 'languages' is missing or empty`);

  // Oracle rule guard: problem.yaml must NOT carry expected outputs.
  for (const [i, c] of spec.cases.entries()) {
    if (c && Object.prototype.hasOwnProperty.call(c, "expected")) {
      throw new Error(
        `${yamlPath}: case ${i + 1} contains an 'expected' value. ` +
          `Expecteds are generated by the oracle, never hand-typed. Remove it.`
      );
    }
    if (!c || typeof c.stdin === "undefined")
      throw new Error(`${yamlPath}: case ${i + 1} has no 'stdin'`);
    if (!c.note)
      throw new Error(
        `${yamlPath}: case ${i + 1} is missing its required 'note' (why this case exists)`
      );
  }

  // Oracle language: use the first declared language that has a solution.
  const language = spec.languages[0];
  const solutionList = spec.solution && spec.solution[language];
  if (!Array.isArray(solutionList) || solutionList.length === 0)
    throw new Error(
      `${yamlPath}: no solution files listed for language '${language}'`
    );
  const solutionPaths = solutionList.map((f) => {
    const p = join(problemDir, f);
    if (!existsSync(p)) throw new Error(`${yamlPath}: solution file not found: ${f}`);
    return p;
  });

  const runner = getRunner(language);
  const results = [];
  try {
    runner.prepare(solutionPaths);
    for (const c of spec.cases) {
      const stdinStr = String(c.stdin);
      const rawOut = runner.run(stdinStr);
      results.push({
        stdin: stdinStr,
        note: c.note,
        expected: normalizeEol(rawOut),
      });
    }
  } finally {
    runner.cleanup();
  }

  return { spec, language, cases: results };
}

// ---------------------------------------------------------------------------
// writers: expected.json (machine) + tests.md (human mirror)
// ---------------------------------------------------------------------------
function expectedArtifact(problemDir, gen) {
  return {
    id: gen.spec.id,
    language: gen.language,
    generated: true,
    note: "GENERATED by the authoring CLI (kh.mjs). Do not edit by hand. Regenerate with `node kh.mjs gen`.",
    cases: gen.cases.map((c) => ({
      stdin: c.stdin,
      note: c.note,
      expected: c.expected,
    })),
  };
}

function renderTestsMd(gen) {
  const title = gen.spec.id ?? "problem";
  const fence = (s) =>
    "`" + s.replace(/\n/g, "\\n") + "`"; // single-line display of multi-line I/O
  const lines = [];
  lines.push(`# Hidden tests, ${title}`);
  lines.push("");
  lines.push(
    "> GENERATED human mirror. Expected values produced by running the reference"
  );
  lines.push(
    "> solution (the oracle), never hand-typed. Regenerate: `node kh.mjs gen`."
  );
  lines.push("> Multiple varied inputs incl. edge cases → a hardcoded literal cannot pass all of them.");
  lines.push("");
  lines.push("| # | stdin | expected stdout | why |");
  lines.push("|---|-------|-----------------|-----|");
  gen.cases.forEach((c, i) => {
    lines.push(
      `| t${i + 1} | ${fence(c.stdin)} | ${fence(c.expected)} | ${c.note} |`
    );
  });
  lines.push("");
  lines.push(
    "Pass condition: stdout matches expected exactly (CRLF→LF normalized) for **all** cases."
  );
  lines.push("");
  return lines.join("\n");
}

function readJsonIfExists(p) {
  if (!existsSync(p)) return null;
  try {
    return JSON.parse(readFileSync(p, "utf8"));
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------------------
// commands
// ---------------------------------------------------------------------------
function cmdGen(targetPath) {
  const dirs = findProblemDirs(targetPath);
  if (dirs.length === 0) {
    console.log("No problem folders found under", targetPath);
    return 0;
  }
  let ok = 0;
  for (const dir of dirs) {
    const rel = relative(process.cwd(), dir);
    try {
      const gen = generateForProblem(dir);
      const artifact = expectedArtifact(dir, gen);
      writeFileSync(
        join(dir, "expected.json"),
        JSON.stringify(artifact, null, 2) + "\n",
        "utf8"
      );
      writeFileSync(join(dir, "tests.md"), renderTestsMd(gen), "utf8");
      console.log(`  generated  ${rel}  (${gen.cases.length} cases)`);
      ok++;
    } catch (err) {
      console.error(`  FAILED     ${rel}\n             ${err.message}`);
      return 1;
    }
  }
  console.log(`\nDone. ${ok}/${dirs.length} problem(s) generated.`);
  return 0;
}

function cmdCheck(targetPath) {
  const dirs = findProblemDirs(targetPath);
  if (dirs.length === 0) {
    console.log("No problem folders found under", targetPath);
    return 0;
  }
  const drifted = [];
  const missing = [];
  for (const dir of dirs) {
    const rel = relative(process.cwd(), dir);
    let gen;
    try {
      gen = generateForProblem(dir);
    } catch (err) {
      console.error(`  ERROR      ${rel}\n             ${err.message}`);
      return 1;
    }
    const fresh = expectedArtifact(dir, gen);
    const committed = readJsonIfExists(join(dir, "expected.json"));
    if (!committed) {
      missing.push(rel);
      console.error(`  MISSING    ${rel}  (no expected.json, run gen)`);
      continue;
    }
    // Compare only the oracle-generated expecteds (and the inputs they map to).
    const freshKey = JSON.stringify(
      fresh.cases.map((c) => [c.stdin, c.expected])
    );
    const committedKey = JSON.stringify(
      (committed.cases ?? []).map((c) => [c.stdin, c.expected])
    );
    if (freshKey !== committedKey) {
      drifted.push(rel);
      console.error(`  DRIFT      ${rel}  (committed expecteds differ from a fresh run)`);
    } else {
      console.log(`  ok         ${rel}`);
    }
  }
  if (drifted.length || missing.length) {
    console.error(
      `\nCHECK FAILED: ${drifted.length} drifted, ${missing.length} missing. ` +
        `Run \`node kh.mjs gen\` and commit.`
    );
    return 1;
  }
  console.log(`\nCHECK OK. ${dirs.length} problem(s) match their committed expecteds.`);
  return 0;
}

// ---------------------------------------------------------------------------
// entry
// ---------------------------------------------------------------------------
function main() {
  const [, , cmd, pathArg] = process.argv;
  const target = pathArg ? resolve(pathArg) : COURSES_ROOT;

  if (cmd === "gen") return cmdGen(target);
  if (cmd === "check") return cmdCheck(target);

  console.log(
    [
      "khouding authoring CLI, the oracle (generates expected outputs).",
      "",
      "Usage:",
      "  node kh.mjs gen   [path]   generate expected.json + tests.md for a problem/section/course",
      "  node kh.mjs check [path]   re-run solutions and fail on drift (CI guard)",
      "",
      "  [path] defaults to ../courses (everything). May point at a single",
      "  problem folder, a section, or a course.",
      "",
      "Examples:",
      "  node kh.mjs gen   ../courses/csharp-basics/sections/1.3-number-variables",
      "  node kh.mjs gen   ../courses/csharp-basics/sections/1.3-number-variables/problems/p01-declare-an-int",
      "  node kh.mjs check",
    ].join("\n")
  );
  return cmd ? 1 : 0;
}

process.exit(main());
